let bad = 0;
const t = (name, got, want) => { const ok = got === want; if (!ok) bad++; console.log((ok ? "OK  " : "CHYBA ") + name + " -> " + got + (ok ? "" : " (čakané " + want + ")")); };
// pôvodné (pokazené) show musia zlyhať, správna oprava musí prejsť
